#!/usr/bin/env python3
"""
make_readme.py — generate README.txt from the verified artefacts
(dataset_statistics.json, sources.json, reports/verification_report.json,
tokenizer/token_stats.json).

Generating the documentation from the measured data keeps the prose and the
numbers in sync; nothing in README.txt is typed by hand.

Usage:
  python3 pipeline/make_readme.py --out README.txt
"""
from __future__ import annotations

import argparse
import json
import os
import textwrap

SOURCE_ORDER = [
    "wikipedia_fa", "pn_summary_news", "persian_news", "parsinlu_entailment",
    "ganjoor_classics", "persian_poetry", "peqa_dialogue", "parsinlu_rc_passage",
    "parsinlu_mc", "parsinlu_qa",
]


def load(path, default=None):
    if path and os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    return default


def fmt(n):
    return f"{n:,}" if isinstance(n, int) else str(n)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--statistics", default="dataset_statistics.json")
    ap.add_argument("--sources", default="sources.json")
    ap.add_argument("--verification", default="reports/verification_report.json")
    ap.add_argument("--tokens", default="tokenizer/token_stats.json")
    ap.add_argument("--out", default="README.txt")
    args = ap.parse_args()

    st = load(args.statistics)["dataset"]
    src = load(args.sources)
    ver = load(args.verification)
    tok = load(args.tokens)

    tot = st["totals"]
    split = st["split"]
    tr, va = st["files"]["train"], st["files"]["validation"]
    by_src = st["source_distribution"]["by_source"]
    clean = st["collection_and_cleaning"]
    dedup = st["deduplication"]

    lines = []
    w = lines.append

    w("=" * 78)
    w("PERSIAN PRETRAINING CORPUS FOR GPT-100M")
    w("مجموعه متن فارسی برای آموزش مدل زبانی GPT با ۱۰۰ میلیون پارامتر")
    w("=" * 78)
    w("")
    w(f"Version      : {st['version']}")
    w(f"Generated    : {st['generated_at_utc']} (UTC)")
    w(f"Collected    : {src['collection_date']}")
    w(f"Language     : Persian (Farsi), standard Iranian Persian")
    w(f"Encoding     : UTF-8 (no BOM), Unix line endings")
    w(f"Files        : train.txt, validation.txt, sources.json, "
      f"dataset_statistics.json, README.txt")
    w("")
    w("This file is generated by pipeline/make_readme.py from the verified JSON")
    w("artefacts in this repository. Every number below was measured with")
    w("pipeline/compute_statistics.py and pipeline/verify_dataset.py.")
    w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("1. WHAT IS IN THE DATASET")
    w("-" * 78)
    w("")
    w(f"  Documents              {fmt(tot['documents'])}")
    w(f"  Unique documents       {fmt(tot['unique_documents'])}")
    w(f"  Characters             {fmt(tot['characters'])}")
    w(f"  Persian letters        {fmt(tot['persian_characters'])}")
    w(f"  Words                  {fmt(tot['words'])}")
    w(f"  Lines                  {fmt(tot['lines'])}")
    w(f"  Sentences              {fmt(tot['sentences'])}")
    w(f"  ZWNJ (نیم‌فاصله)         {fmt(tot['zwnj_occurrences'])}")
    w(f"  Size on disk           {tot['size_mb']:,.2f} MB "
      f"({tot['size_gib']:.3f} GiB)")
    w(f"  Persian letter share   {tot['persian_letter_share_of_letters'] * 100:.2f}% "
      f"of all letters")
    w("                         (the corpus is 100% Persian script: characters outside")
    w("                          the Persian alphabet/punctuation/digit set are removed)")
    w("")

    if tok:
        t = tok["total"]
        w(f"  Tokens (measured)      {fmt(t['tokens'])} tokens")
        w(f"  Characters per token   {t['characters_per_token']}")
        w(f"  Tokenizer              {tok['tokenizer']['type']}, "
          f"vocab {fmt(tok['tokenizer']['vocab_size'])}, file "
          f"{tok['tokenizer']['file']}")
        w("")
        w("  The token count is exact, not an estimate: the shipped tokenizer was")
        w("  applied to every document with Tokenizer.encode_batch() (see")
        w("  tokenizer/token_stats.json). A different vocabulary will give a")
        w("  different count; expect +-10% for a comparable 32k BPE.")
        w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("2. TRAIN / VALIDATION SPLIT")
    w("-" * 78)
    w("")
    w(f"  train.txt        {fmt(tr['documents']):>10} documents  "
      f"{fmt(tr['characters']):>12} chars  {tr['size_mb']:>8.2f} MB  "
      f"({split['train_share_of_characters'] * 100:.2f}%)")
    w(f"  validation.txt   {fmt(va['documents']):>10} documents  "
      f"{fmt(va['characters']):>12} chars  {va['size_mb']:>8.2f} MB  "
      f"({split['validation_share_of_characters'] * 100:.2f}%)")
    w("")
    w("  The split is computed from a salted SHA-1 of the document id, AFTER global")
    w("  deduplication, so no document (and no near-duplicate document) can appear")
    w("  on both sides. Verified: 0 exact and 0 near-duplicate overlaps")
    if ver:
        cs = ver["cross_split"]
        w(f"  (checked {fmt(cs['validation_documents_checked_for_near_duplicates'])} "
          f"validation documents against all train documents with MinHash LSH).")
    w("")
    w("  Validation documents look exactly like training documents on purpose: this")
    w("  is a pretraining corpus, so the validation set measures whether the model")
    w("  generalises across held-out Persian text, not on a different task.")
    w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("3. FILE FORMAT")
    w("-" * 78)
    w("")
    w("  Plain UTF-8 text. Documents are separated by a line containing exactly:")
    w("")
    w("      <|endoftext|>")
    w("")
    w("  So the file looks like:")
    w("")
    w("      <document 1, paragraphs separated by one empty line>")
    w("")
    w("      <|endoftext|>")
    w("")
    w("      <document 2 ...>")
    w("")
    w("  Paragraph structure inside a document is preserved (one empty line between")
    w("  paragraphs). If you prefer another convention, replace the separator, e.g.")
    w("")
    w("      sed 's/^<|endoftext|>$/=====/' train.txt > train_alt.txt")
    w("")
    w("  or simply split on the marker:")
    w("")
    w("      python3 -c \"import sys;print(len(open('train.txt').read().split('\\n\\n<|endoftext|>\\n\\n')))\"")
    w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("4. SOURCES")
    w("-" * 78)
    w("")
    w(f"  {src['number_of_sources']} upstream corpora. Shares below are of the shipped")
    w("  characters; the full per-source detail (URL, license, license URL, raw and")
    w("  filtered counts, drop reasons) is in sources.json.")
    w("")
    w(f"  {'source':<24}{'documents':>10}{'characters':>14}{'share':>8}  type / license")
    w("  " + "-" * 74)
    for sid in SOURCE_ORDER:
        s = by_src.get(sid)
        if not s or s["documents"] == 0:
            continue
        meta = next((x for x in src["sources"] if x["id"] == sid), {})
        w(f"  {sid:<24}{fmt(s['documents']):>10}{fmt(s['characters']):>14}"
          f"{s['share_of_characters'] * 100:>7.1f}%  "
          f"{meta.get('content_type', '')[:34]}")
        w(f"  {'':<24}{'':>10}{'':>14}{'':>8}  license: {meta.get('license', '')[:48]}")
    w("")
    w("  One further source (pn_summary_news, 11,185 articles) was downloaded and")
    w("  REJECTED by the quality gate: its upstream release has every sentence")
    w("  punctuation mark stripped, so it cannot teach sentence boundaries. It is")
    w("  documented in sources.json with status rejected_by_quality_gate.")
    w("")
    w("  Collection method: every corpus was downloaded from its public GitHub")
    w("  repository. No live website was crawled, no robots.txt rule was evaded, no")
    w("  login/paywall was bypassed, and no private or personal data was collected.")
    w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("5. HOW THE DATA WAS CLEANED")
    w("-" * 78)
    w("")
    w(f"  1. Extraction      : {fmt(clean['raw_documents_extracted'])} raw documents")
    w(f"                       ({fmt(src['aggregate']['raw_characters_extracted'])} "
      f"characters) unpacked from the upstream formats")
    w("                       (CSV, TSV, JSONL, tab-separated chat logs, text trees).")
    w(f"  2. Normalization   : Unicode NFKC, Arabic presentation forms folded to base")
    w("                       letters, Arabic ي/ك/ة -> Persian ی/ک/ه, Arabic-Indic and")
    w("                       Latin digits -> Persian digits, diacritics removed,")
    w("                       tatweel/ZWNJ-corrupting characters removed, ZWNJ kept,")
    w("                       whitespace and punctuation spacing repaired, empty brackets")
    w("                       and doubled punctuation repaired, HTML tags, entities,")
    w("                       URLs, e-mails, wiki templates/links/refs removed.")
    w("                       Back-to-back duplicated words and short phrases (a")
    w("                       wiki-link flattening artefact, e.g. 'فیلم ترسناک ترسناک')")
    w("                       are collapsed for prose sources.")
    w("                       Every character outside the Persian alphabet, Persian")
    w("                       digits, Persian punctuation, space/newline and ZWNJ is")
    w("                       dropped, so Latin-script words and emoji do not survive.")
    w(f"  3. Line cleaning   : navigation/boilerplate lines (share buttons, 'کد خبر',")
    w("                       'کلیه حقوق محفوظ', social links, page numbers) dropped;")
    w("                       lines with fewer than 3 Persian letters dropped.")
    w(f"  4. Quality gate    : per-source minimum length, Persian-letter ratio >= 80%,")
    w("                       Latin-letter and digit-ratio caps, sentence-length and")
    w("                       fragment checks, repeated-line and repeated-4-gram checks,")
    w("                       compression-ratio check for numeric/table garbage.")
    w(f"                       -> {fmt(clean['documents_after_quality_filters'])} documents kept")
    w(f"                          ({fmt(clean['characters_after_quality_filters'])} characters)")
    w(f"  5. Deduplication   : {fmt(dedup.get('exact_duplicates', 0))} exact duplicates + "
      f"{fmt(dedup.get('near_duplicates', 0))} near-duplicates removed")
    w("                       (SHA-1 of the normalized text; one-permutation MinHash")
    w("                       over 4-word shingles, 4-band LSH, >=12/16 buckets equal)")
    w(f"                       -> {fmt(dedup.get('output_docs', 0))} unique documents")
    w(f"  6. Budget balance  : per-source caps keep the mix comparable to real-world")
    w("                       Persian text. Wikipedia is sampled per article-length")
    w("                       band (short/medium/long/very long) and ranked by a")
    w("                       quality score inside each band, so the sample keeps")
    w("                       encyclopedic breadth instead of collapsing onto a few")
    w("                       thousand very long articles.")
    w(f"                       -> {fmt(tot['documents'])} documents shipped")
    w("  7. Verification    : independent re-scan of the written files (see section 8).")
    w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("6. LICENSING AND COPYRIGHT")
    w("-" * 78)
    w("")
    w("  The corpus is a compilation of sources under different licenses:")
    w("")
    w("  * CC BY-SA 4.0 (attribution + share-alike)")
    w("      wikipedia_fa        - Wikipedia text, credit to Wikipedia contributors")
    w("      persian_poetry      - classical poems (public domain) + compilation")
    w("  * GPL-3.0 repository / public-domain works")
    w("      ganjoor_classics    - classical Persian literature")
    w("  * MIT")
    w("      peqa_dialogue       - chat pairs")
    w("  * CC BY-NC-SA 4.0 (NonCommercial)")
    w("      parsinlu_qa, parsinlu_mc, parsinlu_entailment, parsinlu_rc_passage")
    w("  * Publisher copyright, research use only")
    w("      persian_news        - news text (c) the original news agencies")
    w("")
    w("  PRACTICAL CONSEQUENCE")
    w("  ---------------------")
    w("  Treat the dataset as RESEARCH / NON-COMMERCIAL material. For commercial use")
    w("  you must drop the NC and publisher-copyright sources. Rebuild a permissive")
    w("  subset with:")
    w("")
    w("      python3 pipeline/build_dataset.py --extracted <work>/extracted \\")
    w("          --tmpdir <work>/build --outdir ./permissive --budget 30000000 \\")
    w("          --only wikipedia_fa ganjoor_classics persian_poetry peqa_dialogue")
    w("")
    w("  Attribution for Wikipedia text (CC BY-SA 4.0) is mandatory if you")
    w("  redistribute: keep this README.txt and sources.json with the data and credit")
    w("  'Wikipedia contributors, CC BY-SA 4.0'.")
    w("  The compilation/cleaning work in this repository is offered under CC BY-SA")
    w("  4.0, without any warranty; the upstream texts keep their own licenses.")
    w("  No license is claimed over the news text, which remains with its publishers.")
    w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("7. KNOWN LIMITATIONS - READ BEFORE TRAINING")
    w("-" * 78)
    w("")
    w("  * Size. The corpus is deliberately capped (see section 9) to stay inside the")
    w("    repository budget. For a 100M-parameter model this is a small corpus:")
    if tok:
        w(f"    {fmt(tok['total']['tokens'])} tokens is well below the ~2B tokens that")
        w("    Chinchilla-style scaling would suggest. Expect to repeat epochs, and")
        w("    expect validation loss to bottom out early; treat it as a starting")
        w("    corpus and extend it as more Persian text becomes available.")
    wiki_share = by_src.get("wikipedia_fa", {}).get("characters", 0) / max(tot["characters"], 1)
    w(f"  * Register skew. Encyclopedic text is {wiki_share * 100:.0f}% of the corpus and")
    w("    journalistic text is another ~10%, so encyclopedic/journalistic registers")
    w("    dominate; dialogue is only a few percent and is informal/colloquial")
    w("    (Tehran chat), so the model will not be equally fluent in every register.")
    poetry_share = (by_src.get("ganjoor_classics", {}).get("characters", 0) +
                    by_src.get("persian_poetry", {}).get("characters", 0)) / max(tot["characters"], 1)
    w(f"  * Poetry. {poetry_share * 100:.1f}% of the corpus is classical verse "
      f"(Rumi, Hafez, Saadi, ...).")
    w("    It is stylistically very different from modern prose; if you want a purely")
    w("    modern-prose model, rebuild without ganjoor_classics/persian_poetry.")
    w("  * Date. The Wikipedia dump is dated 2021-02-01 and the news sources are from")
    w("    roughly 2015-2019, so the model will not know anything later than that.")
    w("  * Format artefacts. Dialogue and QA sources were re-formatted into readable")
    w("    documents ('کاربر: ...', 'پرسش: ...', 'متن نخست: ...'). These markers are")
    w("    part of the text; the model will learn to produce them in dialogue-like")
    w("    contexts. They are a few percent of the corpus.")
    w("  * Informal content. The chat source may contain slang, opinions, politics and")
    w("    occasional profanity; it was not semantically filtered. For a model that")
    w("    must be safe to deploy, filter or drop peqa_dialogue.")
    w("  * Residual link-flattening artefacts. The Wikipedia dump expands piped wiki")
    w("    links by keeping both the target and the label, which occasionally leaves a")
    w("    near-duplicate ('ترکیه ترکیه‌ای', 'دی سی کامیکس دی‌سی کامیکس'). Immediate")
    w("    word/phrase repeats are removed, but variants that differ in spelling or")
    w("    ZWNJ cannot be detected safely and survive in a small share of documents.")
    w("  * No OCR/PDF text, no books published after ~1930 (copyright), no social media")
    w("    beyond the chat corpus.")
    w("  * Normalization choice. Digits are Persian, diacritics are removed, ZWNJ is")
    w("    kept. If your downstream task needs Latin digits, transliterate them.")
    w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("8. VERIFICATION REPORT")
    w("-" * 78)
    w("")
    if ver:
        s = ver["summary"]
        w(f"  Checks run: {s['checks_total']}   passed: {s['checks_passed']}   "
          f"failed: {len(s['checks_failed'])}")
        w("")
        for name, c in ver["checks"].items():
            mark = "PASS" if c.get("pass") else ("n/a " if c.get("pass") is None else "FAIL")
            w(f"    [{mark}] {name}")
        w("")
        w("  Details (counts, examples, longest/shortest documents) are in")
        w("  reports/verification_report.json; randomly sampled documents are in")
        w("  reports/samples.txt for human inspection.")
    else:
        w("  (run pipeline/verify_dataset.py to produce the report)")
    w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("9. WHY THE CORPUS IS CAPPED, AND HOW TO GET MORE")
    w("-" * 78)
    w("")
    w(f"  The cleaning stage produced {fmt(clean['characters_after_quality_filters'])}")
    w("  characters of acceptable Persian text, but this repository is limited to a")
    w("  practical Git artefact size, so the shipped files hold a documented sample")
    w(f"  of {fmt(tot['characters'])} characters. The sampling is deterministic and")
    w("  quality-weighted, and the full cleaned corpus can be regenerated with one")
    w("  command (larger --budget):")
    w("")
    w("      python3 pipeline/build_dataset.py --extracted <work>/extracted \\")
    w("          --tmpdir <work>/build --outdir ./full --budget 450000000")
    w("")
    w("  Nothing is thrown away permanently: the pipeline is reproducible end to end")
    w("  from pipeline/fetch_sources.sh.")
    w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("10. HOW TO REPRODUCE / REBUILD")
    w("-" * 78)
    w("")
    w("      # 1. download the sources (~2 GB, public GitHub repositories only)")
    w("      WORKDIR=/tmp/work bash pipeline/fetch_sources.sh")
    w("")
    w("      # 2. unpack upstream formats into a uniform document stream")
    w("      python3 pipeline/extract_sources.py --workdir /tmp/work \\")
    w("          --out /tmp/work/extracted")
    w("")
    w("      # 3. clean, filter, deduplicate, balance, split")
    w("      python3 pipeline/build_dataset.py --extracted /tmp/work/extracted \\")
    w("          --tmpdir /tmp/work/build --outdir . --budget 45000000")
    w("")
    w("      # 4. statistics and token counts")
    w("      python3 pipeline/compute_statistics.py --manifest /tmp/work/build/selected_manifest.tsv \\")
    w("          --build-report /tmp/work/build/build_report.json \\")
    w("          --token-stats tokenizer/token_stats.json --out dataset_statistics.json")
    w("      python3 pipeline/make_tokenizer.py --out-dir tokenizer")
    w("")
    w("      # 5. verification")
    w("      python3 pipeline/verify_dataset.py")
    w("")
    w("  Requirements: Python 3.9+, standard library only, except tokenizers")
    w("  (pip install tokenizers) for step 4 and py7zr for unpacking the Wikipedia")
    w("  archive. Runtime is ~30 minutes on 2 CPU cores.")
    w("")

    # ------------------------------------------------------------------ #
    w("-" * 78)
    w("11. SAMPLE DOCUMENTS")
    w("-" * 78)
    w("")
    samples_path = "reports/samples.txt"
    if os.path.exists(samples_path):
        txt = open(samples_path, encoding="utf-8").read()
        head = txt.split("=" * 78)[1:7]
        for chunk in head[:2]:
            body = chunk.strip("\n")
            w(body[:1200])
            w("")
    w("  (more samples: reports/samples.txt)")
    w("")
    w("=" * 78)
    w("END OF DOCUMENT")
    w("=" * 78)

    text = "\n".join(lines) + "\n"
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {args.out} ({len(text):,} chars, {len(lines):,} lines)")


if __name__ == "__main__":
    main()
